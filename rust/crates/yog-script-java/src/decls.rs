//! Declarations: the file's class (its methods and fields static), each
//! type nested in it — a class, a struct (copied by `copy()`), a record, an
//! interface, an enum (with data: a sealed interface, a record per case).

use yog_script_analyze::ast::{
    Decl, DeclKind, Generic, Method, Modifier, Param, Pass, Type, TypeHeader,
};

use super::Gen;
use crate::index::Kind;

/// Where a member is written.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Place {
    /// The file's class: everything static.
    File,
    Class,
    Interface,
    /// A record, an enum: no fields of their own.
    Fixed,
}

impl Gen<'_> {
    pub(crate) fn file(&mut self, package: &str, class: &str, decls: &[Decl]) {
        self.code.line(format!(
            "// Generated by yog-script-java from {} — don't edit.",
            self.file
        ));
        self.code.line(format!("package {package};")).blank();
        self.code.open(format!("public final class {class}"));
        self.code.line(format!("private {class}() {{}}"));
        self.members(decls, Place::File);
        self.code.close("");
    }

    pub(crate) fn members(&mut self, decls: &[Decl], place: Place) {
        for d in decls {
            self.decl(d, place);
        }
    }

    pub(crate) fn decl(&mut self, d: &Decl, place: Place) {
        match &d.kind {
            DeclKind::Method(m) => self.method(d, m, place),
            DeclKind::Field(f) if place == Place::File => {
                let t = self.written(&f.ty, false);
                let name = Self::ident(&f.name.text);
                self.code.line(format!("public static {t} {name};"));
                if let Some(v) = &f.value {
                    self.code.open("static");
                    let v = self.expr(v);
                    self.code.line(format!("{name} = {v};"));
                    self.code.close("");
                }
            }
            DeclKind::Field(_) => {}
            DeclKind::Property {
                ty,
                name,
                accessors,
                ..
            } => {
                if let Some(body) = accessors.iter().find_map(|a| a.body.as_ref()) {
                    let head = format!(
                        "public {}{} {}()",
                        stat(place),
                        self.written(ty, false),
                        Self::ident(&name.text)
                    );
                    self.body(&head, Some(body), false);
                }
            }
            DeclKind::Indexer(ix) => self.indexer(d, ix, place),
            DeclKind::Delegate(m) => self.delegate_decl(m),
            DeclKind::Operator(op) => self.method(d, &op.method, place),
            DeclKind::Type {
                word,
                name,
                header,
                body,
                ..
            } => self.type_decl(d, (&word.text, &name.text), header, body),
            DeclKind::Enum {
                name,
                generics,
                variants,
                body,
                ..
            } => self.enum_decl(&name.text, generics, variants, body),
            DeclKind::Mod { name, body } => self.mod_class(d, &name.text, body),
            DeclKind::Namespace {
                body: Some(body), ..
            } => self.members(body, place),
            DeclKind::Ctor(_)
            | DeclKind::Using { .. }
            | DeclKind::Namespace { .. }
            | DeclKind::Alias { .. }
            | DeclKind::Targets(_)
            | DeclKind::Test { .. }
            | DeclKind::Prop(_)
            | DeclKind::Unit { .. } => {}
            _ => self.not_yet("this declaration", decl_span(d)),
        }
    }

    pub(crate) fn method(&mut self, d: &Decl, m: &Method, place: Place) {
        if m.params
            .iter()
            .any(|p| matches!(p.pass, Some(Pass::Ref | Pass::Out)))
        {
            return self.not_yet("a `ref` or `out` parameter", m.name.span);
        }
        let ret = m
            .ret
            .as_ref()
            .map_or_else(|| "void".to_string(), |t| self.written(t, false));
        let void = m.ret.is_none();
        let generics = generic_list(&m.generics);
        let generics = if generics.is_empty() {
            String::new()
        } else {
            format!("{generics} ")
        };
        let params = self.params(&m.params);
        let name = Self::ident(&m.name.text);
        if d.has(Modifier::Extern) {
            return self.service(
                d,
                m,
                &format!("public static {generics}{ret} {name}({params})"),
            );
        }
        let lead = match (place, &m.body) {
            (Place::Interface, None) => String::new(),
            (Place::Interface, Some(_)) if !d.has(Modifier::Static) => "default ".to_string(),
            (Place::File, _) => "public static ".to_string(),
            (_, None) => "public abstract ".to_string(),
            _ => format!("public {}{}", stat_of(d), final_of(d)),
        };
        let head = format!("{lead}{generics}{ret} {name}({params})");
        if m.body.is_none() {
            self.code.line(format!("{head};"));
            return;
        }
        self.body(&head, m.body.as_ref(), void);
    }

    /// `T a, U b`.
    pub(crate) fn params(&mut self, params: &[Param]) -> String {
        params
            .iter()
            .map(|p| {
                format!(
                    "{} {}",
                    self.written(&p.ty, false),
                    Self::ident(&p.name.text)
                )
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    pub(crate) fn type_decl(
        &mut self,
        d: &Decl,
        (word, name): (&str, &str),
        header: &TypeHeader,
        body: &[Decl],
    ) {
        match self.index.kind(name) {
            Some(Kind::Record) => self.record(name, header, body),
            Some(Kind::Interface) => {
                let bases = header
                    .bases
                    .iter()
                    .map(|b| self.written(b, true))
                    .collect::<Vec<_>>();
                let extends = if bases.is_empty() {
                    String::new()
                } else {
                    format!(" extends {}", bases.join(", "))
                };
                self.code.open(format!(
                    "public interface {name}{}{extends}",
                    generic_list(&header.generics)
                ));
                self.members(body, Place::Interface);
                self.code.close("");
            }
            _ => {
                let _ = word;
                self.class(d, name, header, body);
            }
        }
    }

    fn record(&mut self, name: &str, header: &TypeHeader, body: &[Decl]) {
        let params = self.params(header.ctor.as_deref().unwrap_or_default());
        let implements = self.implements(&header.bases);
        self.code.open(format!(
            "public record {name}{}({params}){implements}",
            generic_list(&header.generics)
        ));
        for d in body {
            if matches!(d.kind, DeclKind::Field(_)) {
                self.not_yet("a record's own field", decl_span(d));
            } else {
                self.decl(d, Place::Fixed);
            }
        }
        self.code.close("");
    }

    /// ` implements A, B` for an own type's interfaces.
    fn implements(&self, bases: &[Type]) -> String {
        let all: Vec<String> = bases.iter().map(|b| self.written(b, true)).collect();
        if all.is_empty() {
            String::new()
        } else {
            format!(" implements {}", all.join(", "))
        }
    }
}

/// `<T, U>`, or nothing (lifetimes aside).
pub(crate) fn generic_list(generics: &[Generic]) -> String {
    let names: Vec<&str> = generics
        .iter()
        .filter(|g| !g.lifetime)
        .map(|g| g.name.text.as_str())
        .collect();
    if names.is_empty() {
        String::new()
    } else {
        format!("<{}>", names.join(", "))
    }
}

fn stat(place: Place) -> &'static str {
    if place == Place::File { "static " } else { "" }
}

fn stat_of(d: &Decl) -> &'static str {
    if d.has(Modifier::Static) {
        "static "
    } else {
        ""
    }
}

fn final_of(d: &Decl) -> &'static str {
    if d.has(Modifier::Sealed) {
        "final "
    } else {
        ""
    }
}

pub(crate) fn decl_span(d: &Decl) -> yog_script_analyze::token::Span {
    d.span
}
