//! Declarations: the file's class (its methods and fields static), each
//! type nested in it — a class, a struct (copied by `copy()`), a record, an
//! interface, an enum (with data: a sealed interface, a record per case).

use yog_script_analyze::ast::{
    Accessor, Decl, DeclKind, Generic, Method, Modifier, Param, Pass, Type, TypeHeader,
};
use yog_script_analyze::words::{get, set, value};
use yog_script_ids::clr::ACCESSOR_SEP;

use super::Gen;
use crate::index::Kind;
use crate::modifier;
use yog_script_ids::clr::{RECORD_CLOSE, RECORD_EQ, RECORD_OPEN, RECORD_SEP};
use yog_script_ids::java::{
    ABSTRACT, CLASS, DEFAULT, EXTENDS, FINAL, IMPLEMENTS, INTERFACE, NULL, OVERRIDE, PACKAGE,
    PRIVATE, PROTECTED, PUBLIC, RECORD, RETURN, STATIC, THIS, VOID,
};
use yog_script_ids::jvm::reflection::TYPE;
use yog_script_ids::jvm::{OBJECTS, REF, TO_STRING};

/// Where a member is written.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Place {
    /// The file's class: everything static.
    File,
    Class,
    Interface,
    /// A record, an enum: no fields of their own.
    Fixed,
}

impl Gen<'_> {
    pub(crate) fn file(&mut self, package: &str, class: &str, decls: &[Decl]) {
        self.code.line(format!(
            "// Generated by yog-script-java from {} — don't edit.",
            self.file
        ));
        self.code.line(format!("{PACKAGE} {package};")).blank();
        self.class_name = class.to_string();
        self.code.open(format!("{PUBLIC} {FINAL} {CLASS} {class}"));
        self.code.line(format!("{PRIVATE} {class}() {{}}"));
        self.members(decls, Place::File);
        self.raisers_code();
        self.has_load = self.load_class();
        self.kept_types_constants();
        self.code.close("");
    }

    pub(crate) fn members(&mut self, decls: &[Decl], place: Place) {
        for d in decls {
            self.decl(d, place);
        }
    }

    pub(crate) fn decl(&mut self, d: &Decl, place: Place) {
        let params = self.object_type_params(d);
        let statik = std::mem::replace(
            &mut self.statik,
            place == Place::File || d.has(Modifier::Static),
        );
        self.with_type_params(params, |g| g.decl_kind(d, place));
        self.statik = statik;
    }

    fn decl_kind(&mut self, d: &Decl, place: Place) {
        match &d.kind {
            DeclKind::Method(m) => self.method(d, m, place),
            DeclKind::Field(f) if place == Place::File => {
                let t = self.written(&f.ty, false);
                let name = Self::ident(&f.name.text);
                self.code.line(format!("{PUBLIC} {STATIC} {t} {name};"));
                if let Some(v) = &f.value {
                    self.code.open(STATIC);
                    let v = self.expr(v);
                    self.code.line(format!("{name} = {v};"));
                    self.code.close("");
                }
            }
            DeclKind::Field(_) => {}
            DeclKind::Property {
                ty,
                name,
                accessors,
                ..
            } => {
                let (t, n) = (self.written(ty, false), Self::ident(&name.text));
                self.property_accessors(place, (&t, &n), accessors);
            }
            DeclKind::Indexer(ix) => self.indexer(d, ix, place),
            DeclKind::Event { ty, name } => {
                let t = self.written(ty, true);
                self.event_decl(d, (&t, &name.text), place);
            }
            DeclKind::Delegate(m) => self.delegate_decl(d, m),
            DeclKind::Operator(op) => self.method(d, &op.method, place),
            DeclKind::Type {
                word,
                name,
                header,
                body,
                ..
            } => self.type_decl(d, (&word.text, &name.text), header, body),
            DeclKind::Enum {
                name,
                generics,
                base,
                variants,
                body,
            } => self.enum_decl(d, (&name.text, generics, base.as_ref()), variants, body),
            DeclKind::Mod { name, body } => self.mod_class(d, &name.text, body),
            DeclKind::Command { name, body } => self.command_class(name, body),
            // Its properties are its definition, made by `yog build`; its
            // members, its kind's object's class.
            DeclKind::Content {
                kind,
                name,
                header,
                body,
            } => {
                if body.iter().any(|m| !matches!(m.kind, DeclKind::Prop(_))) {
                    self.content_class(d, (&kind.text, &name.text), header, body);
                }
            }
            DeclKind::Namespace {
                body: Some(body), ..
            } => self.members(body, place),
            DeclKind::Ctor(_)
            | DeclKind::Using { .. }
            | DeclKind::Namespace { .. }
            | DeclKind::Alias { .. }
            | DeclKind::Targets(_)
            | DeclKind::Test { .. }
            | DeclKind::Prop(_)
            | DeclKind::Unit { .. } => {}
            _ => self.not_yet("this declaration", decl_span(d)),
        }
    }

    pub(crate) fn method(&mut self, d: &Decl, m: &Method, place: Place) {
        let ret = m
            .ret
            .as_ref()
            .map_or_else(|| VOID.to_string(), |t| self.written(t, false));
        let void = m.ret.is_none();
        // A static one of an own generic type: generic over its type's
        // parameters too (Java's statics can't reach a class's), handed
        // their values first.
        let class_handed = self.static_type_params(d).unwrap_or_default();
        let mut names: Vec<String> = class_handed.iter().map(|(g, _)| g.clone()).collect();
        names.extend(
            m.generics
                .iter()
                .filter(|g| !g.lifetime)
                .map(|g| g.name.text.clone()),
        );
        let generics = if names.is_empty() {
            String::new()
        } else {
            format!("<{}> ", names.join(", "))
        };
        let params = self.method_params(m);
        let params = class_handed
            .iter()
            .map(|(_, v)| format!("{TYPE} {v}"))
            .chain((!params.is_empty()).then_some(params))
            .collect::<Vec<_>>()
            .join(", ");
        let name = match &self.owner {
            Some(owner) => Self::ident(&self.index.java_name(owner, m)),
            None => Self::ident(&m.name.text),
        };
        if d.has(Modifier::Extern) {
            return self.service(
                d,
                m,
                &format!("{PUBLIC} {STATIC} {generics}{ret} {name}({params})"),
            );
        }
        let lead = match (place, &m.body) {
            (Place::Interface, None) => String::new(),
            (Place::Interface, Some(_)) if !d.has(Modifier::Static) => modifier(DEFAULT),
            (Place::File, _) => modifier(PUBLIC) + &modifier(STATIC),
            (_, None) => modifier(PUBLIC) + &modifier(ABSTRACT),
            _ => format!("{}{}{}", access_of(d), stat_of(d), final_of(d)),
        };
        let head = format!("{lead}{generics}{ret} {name}({params})");
        self.provided(d, m, &name);
        // The file's own (a command's are its ways of running).
        if place == Place::File && !self.in_command {
            self.message_endpoint(d, m);
        }
        if m.body.is_none() {
            self.code.line(format!("{head};"));
            return;
        }
        let outer = std::mem::replace(&mut self.cells, crate::refs::cells(&m.params));
        let generics = Self::method_type_params(m);
        let yields = yog_script_analyze::body_yields(m.body.as_ref());
        if yields {
            let is_async = d.has(Modifier::Async);
            self.with_type_params(generics, |g| g.iterator_method(&head, m, is_async));
        } else if d.has(Modifier::Async) {
            self.with_type_params(generics, |g| g.async_method(&head, m));
        } else {
            self.with_type_params(generics, |g| g.body(&head, m.body.as_ref(), void));
        }
        self.cells = outer;
    }

    /// A property's accessors with bodies as Java's methods: its getter
    /// `Name()`, its setter `set_Name(value)` (the CLR's); an interface's
    /// getter without one.
    fn property_accessors(&mut self, place: Place, (t, n): (&str, &str), accessors: &[Accessor]) {
        let interface = place == Place::Interface;
        let lead = if interface {
            DEFAULT.to_string()
        } else {
            format!("{PUBLIC} {}", stat(place))
        };
        let body_of = |word: &str| {
            accessors
                .iter()
                .find(|a| a.name.text == word)
                .and_then(|a| a.body.as_ref())
        };
        match body_of(get::WORD.text) {
            Some(body) => self.body(&format!("{lead}{t} {n}()"), Some(body), false),
            // An interface's: its getter, its implementers'.
            None if interface => {
                self.code.line(format!("{t} {n}();"));
            }
            None => {}
        }
        if let Some(body) = body_of(set::WORD.text) {
            let head = format!(
                "{lead}{VOID} {}{ACCESSOR_SEP}{n}({t} {})",
                set::WORD.text,
                value::WORD.text
            );
            self.body(&head, Some(body), true);
        }
    }

    /// `T a, U b`.
    pub(crate) fn params(&mut self, params: &[Param]) -> String {
        params
            .iter()
            .map(|p| {
                let t = match p.pass {
                    Some(Pass::Ref | Pass::Out) => {
                        format!("{REF}<{}>", self.written(&p.ty, true))
                    }
                    _ => self.written(&p.ty, false),
                };
                format!("{t} {}", Self::ident(&p.name.text))
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    pub(crate) fn type_decl(
        &mut self,
        d: &Decl,
        (word, name): (&str, &str),
        header: &TypeHeader,
        body: &[Decl],
    ) {
        let arity = header.generics.iter().filter(|g| !g.lifetime).count();
        let outer = self.owner.replace((name.to_string(), arity));
        let inner = std::mem::replace(&mut self.inner_type, outer.is_some());
        let generics = header
            .generics
            .iter()
            .filter(|g| !g.lifetime)
            .map(|g| g.name.text.clone())
            .collect();
        let outer_generics = std::mem::replace(&mut self.owner_generics, generics);
        // A nested type reaches none of its outer one's.
        let outer_params = std::mem::take(&mut self.type_params);
        self.type_of_kind(d, (word, name), header, body);
        self.type_params = outer_params;
        self.owner_generics = outer_generics;
        self.owner = outer;
        self.inner_type = inner;
    }

    fn type_of_kind(
        &mut self,
        d: &Decl,
        (word, name): (&str, &str),
        header: &TypeHeader,
        body: &[Decl],
    ) {
        let arity = header.generics.iter().filter(|g| !g.lifetime).count();
        match self.index.kind(&(name.to_string(), arity)) {
            Some(Kind::Record) => self.record(d, name, header, body),
            Some(Kind::Interface) => {
                let bases = header
                    .bases
                    .iter()
                    .map(|b| self.written(b, true))
                    .collect::<Vec<_>>();
                let extends = if bases.is_empty() {
                    String::new()
                } else {
                    format!(" {EXTENDS} {}", bases.join(", "))
                };
                // Its name in Java: the arity's too, when its name has several
                // (`ILogger1` for `ILogger<T>`).
                let java = self.simple_name(name, header);
                self.code.open(format!(
                    "{PUBLIC} {INTERFACE} {java}{}{extends}",
                    generic_list(&header.generics)
                ));
                self.describe(d);
                self.members(body, Place::Interface);
                self.code.close("");
            }
            _ => {
                let _ = word;
                self.class(d, name, header, body);
            }
        }
    }

    /// A record: Java's, its own fields components after its parameters
    /// (equal, written and copied with them, as C#'s), set from their
    /// values by a constructor of its parameters.
    fn record(&mut self, d: &Decl, name: &str, header: &TypeHeader, body: &[Decl]) {
        let ctor = header.ctor.as_deref().unwrap_or_default();
        let own: Vec<&yog_script_analyze::ast::Field> = body
            .iter()
            .filter(|m| !m.has(Modifier::Static) && !m.has(Modifier::Const))
            .filter_map(|m| match &m.kind {
                DeclKind::Field(f) => Some(f),
                _ => None,
            })
            .collect();
        let mut components = vec![self.params(ctor)];
        components.extend(own.iter().map(|f| {
            format!(
                "{} {}",
                self.written(&f.ty, false),
                Self::ident(&f.name.text)
            )
        }));
        components.retain(|c| !c.is_empty());
        let implements = self.implements(&header.bases);
        self.code.open(format!(
            "{PUBLIC} {RECORD} {name}{}({}){implements}",
            generic_list(&header.generics),
            components.join(", ")
        ));
        self.describe(d);
        self.constants(body);
        if !own.is_empty() {
            self.record_ctor(name, ctor, &own);
        }
        let shown: Vec<(&yog_script_analyze::ast::Name, &Type)> = ctor
            .iter()
            .map(|p| (&p.name, &p.ty))
            .chain(own.iter().map(|f| (&f.name, &f.ty)))
            .collect();
        // Its own `ToString()` stands behind Java's; else .NET's text of it.
        let own_text = body.iter().any(|m| {
            matches!(&m.kind, DeclKind::Method(f) if f.name.text == yog_script_ids::members::TO_STRING && f.params.is_empty())
        });
        if own_text {
            self.code.line(format!(
                "{OVERRIDE} {PUBLIC} {} {TO_STRING}() {{ {RETURN} {}(); }}",
                yog_script_ids::jvm::STRING,
                yog_script_ids::members::TO_STRING
            ));
        } else {
            self.record_text(name, &shown);
        }
        for member in body {
            if !matches!(member.kind, DeclKind::Field(_)) {
                self.decl(member, Place::Fixed);
            }
        }
        self.code.close("");
    }

    /// `Name(params)`: the record made of them, its own fields of their values.
    fn record_ctor(&mut self, name: &str, ctor: &[Param], own: &[&yog_script_analyze::ast::Field]) {
        let mut given: Vec<String> = ctor.iter().map(|p| Self::ident(&p.name.text)).collect();
        for f in own {
            let v = match &f.value {
                Some(v) => self.handed_expr(v),
                None => self.zero_of_written(&f.ty).to_string(),
            };
            given.push(v);
        }
        let params = self.params(ctor);
        self.code.line(format!(
            "{PUBLIC} {name}({params}) {{ {THIS}({}); }}",
            given.join(", ")
        ));
    }

    /// `toString()` as .NET writes a record: `Pos { X = 1, Y = 2 }`, a
    /// `null` as nothing.
    fn record_text(&mut self, name: &str, shown: &[(&yog_script_analyze::ast::Name, &Type)]) {
        let parts: Vec<String> = shown
            .iter()
            .map(|(n, t)| {
                let v = Self::ident(&n.text);
                let typed = match &t.kind {
                    yog_script_analyze::ast::TypeKind::Path { path, args } if args.is_empty() => {
                        path.last()
                            .and_then(|p| yog_script_analyze::builtin_type(&p.text))
                    }
                    _ => None,
                };
                let text = match typed.as_ref().filter(|b| {
                    crate::types::primitive(b).is_some() || **b == yog_script_analyze::Type::Decimal
                }) {
                    Some(b) => self.text_of(Some(b), v),
                    None => format!("{OBJECTS}.{TO_STRING}({v}, \"\")"),
                };
                format!(
                    "{} + {text}",
                    self.code.str(&format!("{}{RECORD_EQ}", n.text))
                )
            })
            .collect();
        let body = if parts.is_empty() {
            self.code
                .str(&format!("{name}{RECORD_OPEN}{}", RECORD_CLOSE.trim_start()))
        } else {
            format!(
                "{} + {} + {}",
                self.code.str(&format!("{name}{RECORD_OPEN}")),
                parts.join(&format!(" + {} + ", self.code.str(RECORD_SEP))),
                self.code.str(RECORD_CLOSE)
            )
        };
        self.code.line(format!(
            "{OVERRIDE} {PUBLIC} {} {TO_STRING}() {{ {RETURN} {body}; }}",
            yog_script_ids::jvm::STRING
        ));
    }

    /// Written type `t`'s value before one's set.
    fn zero_of_written(&self, t: &Type) -> &'static str {
        match &t.kind {
            yog_script_analyze::ast::TypeKind::Path { path, args } if args.is_empty() => path
                .last()
                .and_then(|n| yog_script_analyze::builtin_type(&n.text))
                .map_or(NULL, |b| crate::exprs::zero(&b)),
            _ => NULL,
        }
    }

    /// ` implements A, B` for an own type's interfaces.
    fn implements(&self, bases: &[Type]) -> String {
        let all: Vec<String> = bases.iter().map(|b| self.written(b, true)).collect();
        if all.is_empty() {
            String::new()
        } else {
            format!(" {IMPLEMENTS} {}", all.join(", "))
        }
    }
}

/// `<T, U>`, or nothing (lifetimes aside).
pub(crate) fn generic_list(generics: &[Generic]) -> String {
    let names: Vec<&str> = generics
        .iter()
        .filter(|g| !g.lifetime)
        .map(|g| g.name.text.as_str())
        .collect();
    if names.is_empty() {
        String::new()
    } else {
        format!("<{}>", names.join(", "))
    }
}

fn stat(place: Place) -> String {
    if place == Place::File {
        modifier(STATIC)
    } else {
        String::new()
    }
}

/// A member's access in Java: C#'s `private` and `protected` as Java's,
/// the rest public (`internal` is the mod's, across its packages).
fn access_of(d: &Decl) -> String {
    if d.has(Modifier::Private) {
        modifier(PRIVATE)
    } else if d.has(Modifier::Protected) {
        modifier(PROTECTED)
    } else {
        modifier(PUBLIC)
    }
}

fn stat_of(d: &Decl) -> String {
    if d.has(Modifier::Static) {
        modifier(STATIC)
    } else {
        String::new()
    }
}

fn final_of(d: &Decl) -> String {
    if d.has(Modifier::Sealed) {
        modifier(FINAL)
    } else {
        String::new()
    }
}

pub(crate) fn decl_span(d: &Decl) -> yog_script_analyze::token::Span {
    d.span
}
