//! The runtime's hand-written types' (`[Intrinsic]`, `[Host]`)
//! descriptions: a companion each (`Int32Companion.TYPE`), made from its `.ys`
//! declaration as a compiled type's `$TYPE` is, and `Library`, which finds
//! them by their classes — a built-in's values' too (`int`, `Integer` for
//! `Int32`) — and knows what an array is (`System.Array`, `IList<T>`…).

use yog_script_analyze::ast::Decl;
use yog_script_analyze::{Type, system_type};
use yog_script_ids::jvm::reflection::{
    COMPANION_FIELD, COMPANION_SUFFIX, LIBRARY, LIBRARY_ARRAY, LIBRARY_ARRAY_INTERFACES,
    LIBRARY_OF, LIBRARY_PACKAGE, TYPE,
};
use yog_script_ids::jvm::{ENTRY, MAP, OF_ENTRIES, SUPPLIER};
use yog_script_ids::members::MAKE_GENERIC_TYPE;
use yog_script_ids::system::{ARRAY, ARRAY_INTERFACES};

use super::values::of_class;
use crate::library::SOURCE;
use crate::{Gen, JavaFile};
use yog_script_ids::java::{
    CLASS, CLASS_LITERAL, FINAL, NEW, NULL, PACKAGE, PRIVATE, PUBLIC, RETURN, STATIC,
};

/// How far a map's entries are in from its declaration.
const ENTRY_INDENT: &str = "        ";

/// The companions written so far: each one's name and the classes it describes.
#[derive(Default)]
pub(crate) struct Companions {
    written: Vec<(String, Vec<String>)>,
}

impl Companions {
    /// Hand-written type `d` (`name` of `arity`)'s companion, generated by `g`.
    pub(crate) fn add(&mut self, g: &mut Gen, d: &Decl, (name, arity): (&str, usize)) -> JavaFile {
        let class = g.class_of(name, arity);
        let simple = class.rsplit('.').next().unwrap_or(&class);
        let companion = format!("{simple}{COMPANION_SUFFIX}");
        let declaration = g.declaration(d, &companion).unwrap_or_default();
        g.code.line(format!(
            "// Generated by yog-script-java from {SOURCE} — don't edit."
        ));
        g.code.line(format!("{PACKAGE} {LIBRARY_PACKAGE};")).blank();
        g.code.line(format!(
            "/** `{name}`'s description: its class is the runtime's, written by hand. */"
        ));
        g.code.open(format!("{PUBLIC} {FINAL} {CLASS} {companion}"));
        g.code.line(format!("{PRIVATE} {companion}() {{}}"));
        g.code.blank();
        g.code.line(format!(
            "{PUBLIC} {STATIC} {FINAL} {TYPE} {COMPANION_FIELD} = {declaration};"
        ));
        g.code.blank();
        g.describe_method(d);
        g.code.close("");
        let mut classes = vec![class.clone()];
        for c in value_classes(g, name) {
            if !classes.contains(&c) {
                classes.push(c);
            }
        }
        self.written.push((companion.clone(), classes));
        JavaFile {
            path: java_path(&companion),
            source: std::mem::take(&mut g.code).finish(),
        }
    }

    /// `Library`: every companion by its classes, and arrays' base and interfaces.
    pub(crate) fn library(&self, g: &mut Gen) -> JavaFile {
        let entries: Vec<String> = self
            .written
            .iter()
            .flat_map(|(companion, classes)| {
                classes.iter().map(move |c| {
                    format!(
                        "{MAP}.{ENTRY}({c}{CLASS_LITERAL}, () -> {companion}.{COMPANION_FIELD})"
                    )
                })
            })
            .collect();
        g.code.line(format!(
            "// Generated by yog-script-java from {SOURCE} — don't edit."
        ));
        g.code.line(format!("{PACKAGE} {LIBRARY_PACKAGE};")).blank();
        g.code.line("/** The runtime's hand-written types' descriptions by their classes, and what an array is. */");
        g.code.open(format!("{PUBLIC} {FINAL} {CLASS} {LIBRARY}"));
        g.code.line(format!("{PRIVATE} {LIBRARY}() {{}}"));
        g.code.blank();
        g.code.line(format!(
            "{PRIVATE} {STATIC} {FINAL} {MAP}<Class<?>, {SUPPLIER}<{TYPE}>> TYPES = {MAP}.{OF_ENTRIES}("
        ));
        let last = entries.len().saturating_sub(1);
        for (i, e) in entries.iter().enumerate() {
            let end = if i == last { ");" } else { "," };
            g.code.line(format!("{ENTRY_INDENT}{e}{end}"));
        }
        g.code.blank();
        g.code
            .open(format!("{PUBLIC} {STATIC} {TYPE} {LIBRARY_OF}(Class<?> c)"));
        g.code.line(format!("{SUPPLIER}<{TYPE}> t = TYPES.get(c);"));
        g.code
            .line(format!("{RETURN} t == {NULL} ? {NULL} : t.get();"));
        g.code.close("");
        g.code.blank();
        g.code
            .open(format!("{PUBLIC} {STATIC} {TYPE} {LIBRARY_ARRAY}()"));
        g.code
            .line(format!("{RETURN} {};", of_class(&g.index.place(ARRAY, 0))));
        g.code.close("");
        g.code.blank();
        let interfaces: Vec<String> = ARRAY_INTERFACES
            .iter()
            .map(|i| format!("{}.{MAKE_GENERIC_TYPE}(of)", of_class(&g.index.place(i, 1))))
            .collect();
        g.code.open(format!(
            "{PUBLIC} {STATIC} {TYPE}[] {LIBRARY_ARRAY_INTERFACES}({TYPE} element)"
        ));
        g.code.line(format!("{TYPE}[] of = {{ element }};"));
        g.code.line(format!(
            "{RETURN} {NEW} {TYPE}[] {{ {} }};",
            interfaces.join(", ")
        ));
        g.code.close("");
        g.code.close("");
        JavaFile {
            path: java_path(LIBRARY),
            source: std::mem::take(&mut g.code).finish(),
        }
    }
}

/// A built-in type's values' classes in Java (`int`, `Integer` for
/// `Int32`): what `Type.Of` finds it by. An unsigned one's are its signed
/// one's (`u8` is an `int`), so it has none of its own.
fn value_classes(g: &Gen, name: &str) -> Vec<String> {
    let Some(t) = system_type(name) else {
        return Vec::new();
    };
    if matches!(t, Type::U8 | Type::U16 | Type::U32 | Type::U64) {
        return Vec::new();
    }
    vec![g.java(&t, false), g.java(&t, true)]
}

/// Where companion `class` is under the source root.
fn java_path(class: &str) -> String {
    format!("{}/{class}.java", LIBRARY_PACKAGE.replace('.', "/"))
}
